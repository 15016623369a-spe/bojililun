import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/Library/Caches/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-mac-arm64/chrome-headless-shell';
const b = await chromium.launch({ executablePath: exe, args: ['--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3 });
await p.goto('http://127.0.0.1:3002/body', { waitUntil: 'domcontentloaded', timeout: 180000 });
await p.waitForTimeout(16000);
const c = await p.locator('canvas').first().boundingBox();
await p.mouse.move(c.x + c.width * 0.5, c.y + c.height * 0.5);
await p.mouse.down();
await p.mouse.move(c.x + c.width * 0.5 + 330, c.y + c.height * 0.5, { steps: 18 });
await p.mouse.up();
await p.waitForTimeout(1200);
await p.screenshot({ path: '../shots-check/eco-front.png' });
await p.mouse.click(c.x + c.width * 0.46, c.y + c.height * 0.30);
await p.waitForTimeout(2200);
await p.screenshot({ path: '../shots-check/eco-sheet.png' });
await b.close();
